#include "timer.h"
#include "rcc.h"

#define TIMER_TIMEOUT_COUNT 1000000UL

static uint8_t timer2_status = TIMER_OK;

uint8_t TIMER2_Init(uint16_t prescaler, uint16_t auto_reload)
{
    /*
     * TIM2 is on APB1.
     */
    uint32_t timer_clock = RCC_GetAPB1TimerClock();

    if (timer_clock == 0U)
    {
        timer2_status = TIMER_ERROR;
        return TIMER_ERROR;
    }

    /*
     * Enable TIM2 clock.
     */
    RCC->APB1ENR |= RCC_APB1ENR_TIM2EN;

    /*
     * Stop timer while configuring.
     */
    TIM2->CR1 = 0U;

    /*
     * Configure prescaler and auto-reload.
     */
    TIM2->PSC = prescaler;
    TIM2->ARR = auto_reload;

    /*
     * Generate an update event so the PSC value is loaded.
     */
    TIM2->EGR = TIM_EGR_UG;

    /*
     * Clear update flag generated by UG.
     */
    TIM2->SR &= ~TIM_SR_UIF;

    /*
     * Enable auto-reload preload.
     */
    TIM2->CR1 |= TIM_CR1_ARPE;

    timer2_status = TIMER_OK;

    return TIMER_OK;
}

void TIMER2_Start(void)
{
    TIM2->CR1 |= TIM_CR1_CEN;
}

void TIMER2_Stop(void)
{
    TIM2->CR1 &= ~TIM_CR1_CEN;
}

void TIMER2_Reset(void)
{
    TIM2->CNT = 0U;
    TIM2->SR &= ~TIM_SR_UIF;
}

uint16_t TIMER2_GetCounter(void)
{
    return (uint16_t)(TIM2->CNT & 0xFFFFU);
}

uint8_t TIMER2_GetUpdateFlag(void)
{
    if ((TIM2->SR & TIM_SR_UIF) != 0U)
    {
        return 1U;
    }

    return 0U;
}

void TIMER2_ClearUpdateFlag(void)
{
    TIM2->SR &= ~TIM_SR_UIF;
}

uint8_t TIMER2_DelayMs(uint32_t milliseconds)
{
    uint32_t remaining;
    uint32_t timeout;

    if (milliseconds == 0U)
    {
        return TIMER_OK;
    }

    /*
     * TIMER2_DelayMs() is intentionally based on the
     * configured timer update period.
     *
     * For a 1 ms delay tick, configure TIM2 as:
     *
     *   TIMER2_Init((timer_clock / 1000000U) - 1U, 999U)
     *
     * which produces a 1 MHz counter and a 1 ms update.
     *
     * This function therefore waits for one update event
     * per millisecond.
     */

    if (TIM2->ARR != 999U)
    {
        timer2_status = TIMER_ERROR;
        return TIMER_ERROR;
    }

    TIMER2_Reset();
    TIMER2_Start();

    remaining = milliseconds;

    while (remaining != 0U)
    {
        timeout = TIMER_TIMEOUT_COUNT;

        while ((TIM2->SR & TIM_SR_UIF) == 0U)
        {
            if (timeout == 0U)
            {
                TIMER2_Stop();
                timer2_status = TIMER_TIMEOUT;
                return TIMER_TIMEOUT;
            }

            timeout--;
        }

        TIM2->SR &= ~TIM_SR_UIF;

        remaining--;
    }

    TIMER2_Stop();

    timer2_status = TIMER_OK;

    return TIMER_OK;
}

uint8_t TIMER2_GetStatus(void)
{
    return timer2_status;
}
