#include "pwm.h"
#include "gpio.h"
#include "rcc.h"

#define PWM_MAX_DUTY       100U
#define PWM_COUNTER_HZ     1000000UL
#define PWM_MAX_FREQUENCY  1000000UL

static uint8_t pwm_duty_cycle = 0U;
static uint32_t pwm_frequency = 0U;
static uint8_t pwm_status = PWM_OK;

static uint32_t PWM_DivideU32(
    uint32_t dividend,
    uint32_t divisor)
{
    uint32_t quotient = 0U;
    uint32_t remainder = 0U;
    uint32_t i;

    if (divisor == 0U)
    {
        return 0U;
    }

    for (i = 32U; i > 0U; i--)
    {
        remainder <<= 1U;

        if ((dividend & 0x80000000UL) != 0U)
        {
            remainder |= 1U;
        }

        dividend <<= 1U;
        quotient <<= 1U;

        if (remainder >= divisor)
        {
            remainder -= divisor;
            quotient |= 1U;
        }
    }

    return quotient;
}

uint8_t PWM_Init(uint32_t frequency_hz)
{
    uint32_t timer_clock;
    uint32_t prescaler;
    uint32_t period;

    if ((frequency_hz == 0U) ||
        (frequency_hz > PWM_MAX_FREQUENCY))
    {
        pwm_status = PWM_ERROR;
        return PWM_ERROR;
    }

    timer_clock = RCC_GetAPB1TimerClock();

    if (timer_clock == 0U)
    {
        pwm_status = PWM_ERROR;
        return PWM_ERROR;
    }

    /*
     * TIM2_CH1 uses PA0.
     *
     * PA0 is configured as alternate-function push-pull.
     */
    RCC_EnablePeripheralClock(RCC_GPIOA);

    GPIO_Init(
        GPIO_PORT_A,
        PWM_OUTPUT_PIN,
        GPIO_MODE_OUTPUT_50MHZ,
        GPIO_OUTPUT_AF_PP
    );

    /*
     * Enable TIM2.
     */
    RCC->APB1ENR |= RCC_APB1ENR_TIM2EN;

    /*
     * Configure the timer to approximately 1 MHz.
     *
     * PSC = timer_clock / 1 MHz - 1
     */
    if (timer_clock < PWM_COUNTER_HZ)
    {
        pwm_status = PWM_ERROR;
        return PWM_ERROR;
    }

    prescaler =
        PWM_DivideU32(timer_clock, PWM_COUNTER_HZ);

    if (prescaler == 0U)
    {
        prescaler = 1U;
    }

    prescaler--;

    if (prescaler > 0xFFFFU)
    {
        pwm_status = PWM_ERROR;
        return PWM_ERROR;
    }

    /*
     * ARR = counter_clock / frequency - 1
     */
    uint32_t counter_clock =
        PWM_DivideU32(
            timer_clock,
            prescaler + 1U
        );

    period =
        PWM_DivideU32(
            counter_clock,
            frequency_hz
        );

    if (period == 0U)
    {
        pwm_status = PWM_ERROR;
        return PWM_ERROR;
    }

    period--;

    if (period > 0xFFFFU)
    {
        pwm_status = PWM_ERROR;
        return PWM_ERROR;
    }

    /*
     * Stop timer while configuring.
     */
    TIM2->CR1 = 0U;

    TIM2->PSC = (uint16_t)prescaler;
    TIM2->ARR = (uint16_t)period;

    /*
     * PWM mode 1 on channel 1.
     *
     * OC1M = 110
     * OC1PE = 1
     */
    TIM2->CCMR1 &= ~(
        TIM_CCMR1_CC1S |
        TIM_CCMR1_OC1M |
        TIM_CCMR1_OC1PE
    );

    TIM2->CCMR1 |=
        TIM_CCMR1_OC1M_1 |
        TIM_CCMR1_OC1M_2 |
        TIM_CCMR1_OC1PE;

    /*
     * Enable channel 1 output.
     */
    TIM2->CCER |= TIM_CCER_CC1E;

    /*
     * Enable auto-reload preload.
     */
    TIM2->CR1 |= TIM_CR1_ARPE;

    /*
     * Start with 0% duty.
     */
    TIM2->CCR1 = 0U;

    /*
     * Load PSC/ARR/CCR immediately.
     */
    TIM2->EGR = TIM_EGR_UG;

    /*
     * Clear update flag generated by UG.
     */
    TIM2->SR &= ~TIM_SR_UIF;

    pwm_duty_cycle = 0U;
    pwm_frequency = frequency_hz;
    pwm_status = PWM_OK;

    return PWM_OK;
}

void PWM_Start(void)
{
    TIM2->CR1 |= TIM_CR1_CEN;
}

void PWM_Stop(void)
{
    TIM2->CR1 &= ~TIM_CR1_CEN;
}

uint8_t PWM_SetDutyCycle(uint8_t duty_cycle)
{
    uint32_t period;
    uint32_t compare;

    if (duty_cycle > PWM_MAX_DUTY)
    {
        pwm_status = PWM_ERROR;
        return PWM_ERROR;
    }

    period = (uint32_t)TIM2->ARR;

    /*
     * CCR1 = duty% of timer period.
     */
    compare =
        PWM_DivideU32(
            (period + 1U) * (uint32_t)duty_cycle,
            PWM_MAX_DUTY
        );

    if (compare > (period + 1U))
    {
        compare = period + 1U;
    }

    TIM2->CCR1 = compare;

    pwm_duty_cycle = duty_cycle;
    pwm_status = PWM_OK;

    return PWM_OK;
}

uint8_t PWM_GetDutyCycle(void)
{
    return pwm_duty_cycle;
}

uint32_t PWM_GetFrequency(void)
{
    return pwm_frequency;
}

uint8_t PWM_GetStatus(void)
{
    return pwm_status;
}
